import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> args) async {
  final options = _ManifestGeneratorOptions.parse(args);
  final input = Directory(options.inputDirectory);
  if (!await input.exists()) {
    stderr.writeln('Input directory does not exist: ${options.inputDirectory}');
    exitCode = 64;
    return;
  }

  final entries = <_ManifestEntry>[];
  await for (final entity in input.list(recursive: true, followLinks: false)) {
    if (entity is! File || !_isContentFile(entity)) {
      continue;
    }
    entries.add(
      _ManifestEntry(
        path: _relativePath(entity.uri, input.uri),
        content: await entity.readAsString(),
      ),
    );
  }
  entries.sort((left, right) => left.path.compareTo(right.path));

  final output = File(options.outputFile);
  await output.parent.create(recursive: true);
  await output.writeAsString(_emitDart(options.constantName, entries));
}

bool _isContentFile(File file) {
  return file.path.endsWith('.md') || file.path.endsWith('.mdx');
}

String _relativePath(Uri file, Uri root) {
  final rootPath = root.toFilePath(windows: false);
  final filePath = file.toFilePath(windows: false);
  return filePath.substring(rootPath.length).replaceAll(RegExp(r'^/+'), '');
}

String _emitDart(String constantName, List<_ManifestEntry> entries) {
  final buffer = StringBuffer()
    ..writeln('// Generated by dart_edge_docs:generate_docs_manifest.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('const $constantName = <String, String>{');

  for (final entry in entries) {
    buffer
      ..write('  ')
      ..write(jsonEncode(entry.path))
      ..write(': ')
      ..write(jsonEncode(entry.content))
      ..writeln(',');
  }

  buffer.writeln('};');
  return buffer.toString();
}

final class _ManifestEntry {
  const _ManifestEntry({required this.path, required this.content});

  final String path;
  final String content;
}

final class _ManifestGeneratorOptions {
  const _ManifestGeneratorOptions({
    required this.inputDirectory,
    required this.outputFile,
    required this.constantName,
  });

  final String inputDirectory;
  final String outputFile;
  final String constantName;

  static _ManifestGeneratorOptions parse(List<String> args) {
    String? input;
    String? output;
    var constantName = 'dartEdgeDocsContentManifest';

    for (var index = 0; index < args.length; index += 1) {
      final arg = args[index];
      switch (arg) {
        case '--input':
          input = _readValue(args, index += 1, arg);
        case '--output':
          output = _readValue(args, index += 1, arg);
        case '--name':
          constantName = _readValue(args, index += 1, arg);
        case '--help' || '-h':
          _printUsage();
          exit(0);
        default:
          stderr.writeln('Unknown option: $arg');
          _printUsage();
          exit(64);
      }
    }

    if (input == null || output == null) {
      _printUsage();
      exit(64);
    }

    return _ManifestGeneratorOptions(
      inputDirectory: input,
      outputFile: output,
      constantName: constantName,
    );
  }

  static String _readValue(List<String> args, int index, String option) {
    if (index >= args.length) {
      stderr.writeln('Missing value for $option');
      exit(64);
    }
    return args[index];
  }

  static void _printUsage() {
    stderr.writeln(
      'Usage: dart run dart_edge_docs:generate_docs_manifest '
      '--input content/docs --output lib/src/generated/docs_content_manifest.dart '
      '[--name docsContentManifest]',
    );
  }
}
